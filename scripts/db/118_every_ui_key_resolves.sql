-- 118 — Every key the frontend asks for resolves.
--
-- The frontend loads /api/ui-labels/main and nothing else, and the API walks
-- slot -> binding -> label (domain main) -> translation. Measured 2026-09-20,
-- on a fresh install and on the production database alike: 111 of the keys
-- dpmtf-app.js and index.html ask for fell out of that walk, and the UI had
-- shown their hardcoded fallbacks — English, or Danish in System Setup — in
-- every locale. Three causes:
--
-- 1. 20 labels sit in the domain `template_manager`. They have slots,
--    bindings and translations; nothing has fetched that domain since the
--    template manager became part of the main page. Moved to `main`.
--
-- 2. 55 keys had no label at all. LBL-1000546..1000600 are new, in the four
--    mandatory locales; the English text is the fallback the code carried.
--    Nine of them already had a slot, bound to the label that did not exist.
--    Four had been seeded under label ids a later seed reuses
--    (LBL-1000228/229/317/318) and were replaced on every run; that is
--    corrected in init_db.py in the same commit. LBL-1000601..604 are four
--    words System Setup had hardcoded in Danish (unknown, passed, warnings,
--    failed); dpmtf-app.js asks for them from this commit on.
--
-- 3. Labels in `main` had no slot bound to them: 28 the code names, and all
--    of System Setup, whose button keys the frontend builds at run time.
--    Statement 3 gives every active `main` label that no slot reaches a slot
--    of its own name. It is written as a rule, not a list, so it also covers
--    a database whose labels differ from a fresh install; it never touches a
--    slot that is already bound (one label per slot, migration 117).
--
-- Rollback: rollbacks/118_every_ui_key_resolves_rollback.sql

